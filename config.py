class Config:
    """
    設定値。インスタンス化はせず、クラス変数として直接参照する。
    """

    # ------------------------------------------------------------------
    # 植物領域（稲＋雑草）の抽出
    #
    # ここでのExG＋Otsuは「植物とそれ以外」を分けるために使う。
    # 画像に植物と非植物が両方写っている場面ではOtsuは妥当に働く。
    # ------------------------------------------------------------------

    # HSVの閾値（植物として拾う範囲）
    HSV_LOWER = (25, 25, 20)
    HSV_UPPER = (100, 255, 255)

    # CLAHE
    CLAHE_CLIP = 2.0
    CLAHE_GRID = (8, 8)

    # Morphology
    OPEN_KERNEL = (3, 3)
    CLOSE_KERNEL = (5, 5)

    OPEN_ITER = 2
    CLOSE_ITER = 2

    # Connected Components
    MIN_COMPONENT = 80

    # ------------------------------------------------------------------
    # 稲/雑草の分離（彩度による）
    #
    # 雑草の穂は白っぽく彩度が低く、稲の葉は彩度が高い。
    # 植物領域の中を彩度で二分し、低彩度側を雑草とする。
    #
    # 彩度は「元画像」から求める（CLAHEは明度補正のために植物領域の
    # 抽出だけに用い、彩度の判定には使わない）。
    #
    # ※ 以前はExGをOtsuで二値化し、coreに囲まれた穴をpale＝雑草と
    #   していたが、Otsuは「2クラスある」前提で必ず分割するため、
    #   画面が植物一色の画像では稲自身を明暗で二分してしまい、
    #   雑草ゼロの水田で雑草が大量に湧いていた。
    #   またこの方式は草冠より上に突き出た穂（周囲が背景なので
    #   coreに囲まれない）を構造的に検出できなかった。
    # ------------------------------------------------------------------

    # 彩度閾値。これ未満を雑草とする。
    # 配布テスト画像10枚では45〜70のどこでも4レベルが完全分離する。
    # 隣接レベル間の余裕（絶対値・比のいずれでも）が最大となる65を採用。
    SATURATION_THRESHOLD = 65

    # 雑草領域から除去する微小連結成分の面積（0で無効）
    WEED_MIN_COMPONENT = 0

    # 出力画像の色（BGR）
    BACKGROUND = (0, 0, 0)
    RICE = (128, 128, 128)
    WEED = (255, 255, 255)

    # ------------------------------------------------------------------
    # 判定閾値
    #
    # 配布テスト画像10枚の雑草比率（彩度閾値65）:
    #   レベル0: 0.01 / 0.02 / 0.11 / 0.49
    #   レベル1: 0.94 / 1.10
    #   レベル2: 1.77 / 1.79
    #   レベル3: 2.56 / 19.13
    # 各境界の中点を閾値とする。
    #
    # ※ 根拠が10枚しかないため、閾値は暫定値である。テスト画像が
    #   追加で入手できた場合は、雑草比率の分布を見て引き直すこと。
    # ------------------------------------------------------------------

    LEVEL0 = 0.70
    LEVEL1 = 1.45
    LEVEL2 = 2.15